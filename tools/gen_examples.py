"""Writes web/js/examples.js from the Ubuntu app's example events (placeholder officials only)."""
import json, sys, os
src = sys.argv[1]
names = {"example_q3": ("Elite back-to-back – standard distance (example)",
                        "Two Elite standard-distance races back to back: swim 2 laps, bike 8 laps, run 2 laps, 2 wheel stations, "
                        "2 aid stations. Times follow the Masterfile back-to-back schedule (10:00 and 12:45). 18 placeholder officials."),
         "example_multiday": ("Two-day weekend – sprint + mixed relay (example)", None)}
out = {}
for key, (title, notes) in names.items():
    ev = json.load(open(os.path.join(src, key + ".wtplan.json")))
    ev["event"]["name"] = title
    if notes: ev["event"]["notes"] = notes
    ev["event"]["notes"] = ev["event"]["notes"].replace("World Cup ", "")
    out[key] = ev
p = os.path.join(os.path.dirname(__file__), "..", "web", "js", "examples.js")
with open(p, "w", encoding="utf-8") as f:
    f.write("/* Example events (generated by tools/gen_examples.py). Officials are placeholders. */\n")
    f.write("var WTP = (typeof WTP !== 'undefined') ? WTP : {};\nWTP.examples = " + json.dumps(out, ensure_ascii=False) + ";\n")
    f.write("if (typeof module !== 'undefined') module.exports = WTP;\n")
print("wrote", p)
